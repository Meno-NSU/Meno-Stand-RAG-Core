import json
import math
from typing import Any

SYSTEM_PROMPT_FOR_RELEVANCE = """Вы — система оценки релевантности документов поисковым запросам. Ваша задача состоит в том, чтобы классифицировать пару «поисковый запрос — документ» строго в один из трёх классов релевантности.

## Классы релевантности

- **2** — высокая релевантность: фрагменты документа содержат подробную, развёрнутую информацию, непосредственно отвечающую на поисковый запрос пользователя. Основная тема документа совпадает с темой запроса. Также совпадают ключевые именованные сущности запроса (фамилии людей, названия организаций) с тем, что упомянуто в документе.
- **1** — средняя релевантность: фрагменты документа частично затрагивают тему запроса, содержат косвенно связанную информацию или упоминают предмет запроса вскользь, без подробного раскрытия.
- **0** — нет релевантности: фрагменты документа не имеют смыслового отношения к поисковому запросу. Информация в документе не помогает ответить на запрос пользователя.

## Правила оценки именованных сущностей

При оценке релевантности по упоминаниям людей, организаций, мест и других именованных сущностей соблюдайте следующие приоритеты:

1. **Фамилия — главный идентификатор человека.** Совпадение фамилии значительно важнее совпадения имени или отчества. Если в запросе указана фамилия, а в документе встречается та же фамилия (даже без имени и отчества), документ может быть высокорелевантным и должен быть отнесён к классу релевантности **2**.
2. **Совпадение только имени и/или отчества без совпадения фамилии не является признаком релевантности.** Имена и отчества широко распространены и сами по себе не идентифицируют конкретного человека. Например, если в запросе упомянут «Александр Николаевич Люлько», а в документе — «Александр Николаевич Иванов», это разные люди, и документ нерелевантен по данному признаку.
3. **Неполное совпадение ФИО при совпадении фамилии:** если в документе упомянута только фамилия (например, «Люлько») без имени и отчества, а в запросе указано полное ФИО («Александр Николаевич Люлько»), то документ потенциально релевантен, так как речь может идти о том же человеке.
4. **Аналогичные принципы для организаций, проектов, продуктов:** ключевое собственное название (бренд, название проекта, название организации) является главным идентификатором. Совпадение общих слов (например, «нейросеть», «факультет») без совпадения собственного названия не свидетельствует о релевантности. Например, если в запросе упомянут «факультет информационных технологий», а в документе — «механико-математический факультет», это разные факультеты, и документ нерелевантен по данному признаку. В то же время если в запросе упомянут просто «факультет» без конкретизации (например, «Какие факультеты есть в университете?»), то здесь уже документ с описанием любого факультета будет релевантен запросу.

## Правила общей оценки

- Оценивайте смысловое соответствие, а не поверхностное совпадение отдельных слов (кроме совпадения фамилий, поскольку такое совпадение, как было отмечено выше, может свидетельствовать о высокой релевантности запроса документу).
- Учитывайте название документа, аннотацию и все предоставленные фрагменты в совокупности.
- Если запрос задаёт конкретный вопрос, оценивайте, насколько документ помогает на него ответить.
- Если запрос содержит указание на конкретную тему, персону или объект, а документ посвящён совершенно другой теме, персоне или объекту — это класс релевантности **0**, даже если есть случайные пересечения по служебным словам.

## Формат ответа

Ответьте строго одним символом: 2, 1 или 0. Не добавляйте никаких пояснений, комментариев или дополнительного текста.
"""

MAX_RERANKER_TOKENS: int = 8192
POSSIBLE_LABELS = ["0", "1", "2"]


def build_prompt(search_query: str, estimated_document: str, is_json: bool = False) -> list[dict[str, str]]:
    user_prompt = "**Поисковый запрос пользователя:** " + " ".join(search_query.strip().split()) + "\n\n"
    user_prompt += estimated_document.strip() + "\n\n**Ваша оценка релевантности:**\n"
    if is_json:
        modified_chapter_name = "## Формат ответа"
        found_idx = SYSTEM_PROMPT_FOR_RELEVANCE.find(modified_chapter_name)
        if found_idx < 0:
            raise RuntimeError(f"The system prompt does not contain the chapter `{modified_chapter_name}`.")
        modified_system_prompt = SYSTEM_PROMPT_FOR_RELEVANCE[:found_idx] + modified_chapter_name + "\n\n"
        modified_system_prompt += (
            'Ответьте в формате JSON вида `{"label": <your_label>}`, где '
            "`<your_label>` — это цифра 2, 1 или 0. Не добавляйте никаких пояснений, "
            "комментариев или дополнительного текста.\n"
        )
        return [{"role": "system", "content": modified_system_prompt}, {"role": "user", "content": user_prompt}]
    return [{"role": "system", "content": SYSTEM_PROMPT_FOR_RELEVANCE}, {"role": "user", "content": user_prompt}]


def score_from_logprobs(choice: dict[str, Any]) -> float:
    try:
        top_logprobs_list = choice["logprobs"]["content"][0]["top_logprobs"]
    except (KeyError, TypeError, IndexError) as exc:
        raise ValueError("Reranker response does not contain top_logprobs.") from exc

    token_to_logprob = {str(item["token"]): float(item["logprob"]) for item in top_logprobs_list if "token" in item}
    raw = {label: token_to_logprob.get(label, -100.0) for label in POSSIBLE_LABELS}
    max_lp = max(raw.values())
    exp_values = {k: math.exp(v - max_lp) for k, v in raw.items()}
    total = sum(exp_values.values())
    probs = {k: v / total for k, v in exp_values.items()}
    predicted_class = int(max(probs, key=probs.get))
    if predicted_class == 2:
        return probs["2"]
    return 0.0


def score_from_json_response(content: str) -> float:
    parsed = json.loads(content.strip())
    label = str(parsed["label"]).strip()
    if label == "2":
        return 1.0
    return 0.0


def rerank_merge_score(retrieval_score: float, rerank_score: float, alpha: float) -> float:
    if rerank_score > 0.0:
        return (1.0 - alpha) * retrieval_score + alpha * rerank_score
    return rerank_score


def response_format_schema() -> dict[str, Any]:
    return {
        "type": "json_schema",
        "json_schema": {
            "name": "relevance",
            "schema": {
                "type": "object",
                "properties": {
                    "label": {
                        "type": "string",
                        "enum": ["0", "1", "2"],
                    }
                },
                "required": ["label"],
                "additionalProperties": False,
            },
            "strict": True,
        },
    }
